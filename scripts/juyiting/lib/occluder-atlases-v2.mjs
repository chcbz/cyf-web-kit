/**
 * E9B deterministic six-region occluder atlas generation core.
 *
 * This module is strictly mechanical: it consumes the frozen E9A fragment
 * ownership spec and copies canonical RGBA only for ownershipRuns, clears
 * every other sourceRect pixel to transparent, packs fragments into one atlas
 * per homeRegion, encodes lossless deterministic PNG, and verifies that
 * reconstructing the full 1664x928 frame from the atlases is pixel-exact
 * against the canonical decode (0 missing / 0 overlap / 0 channel mismatch).
 *
 * No visual semantics are judged here. All packing, encoding, and evidence
 * parameters are recorded in the E9B manifest and golden report so the whole
 * pipeline can be regenerated byte-for-byte.
 */
