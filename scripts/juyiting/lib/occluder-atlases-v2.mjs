/**
 * Decodes a WebP byte stream to un-premultiplied RGBA via headless Chromium.
 * Deterministic for a fixed decoder build (verified across runs).
 */
export function decodeCanonicalRgba(webpBytes, { chromium = CHROMIUM } = {}) {
  const sourceSha256 = sha256(webpBytes)
  const nonce = `${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}`
  const htmlPath = join(tmpdir(), `e9b-rgba-decode-${nonce}.html`)
  const html = `<!doctype html><meta charset="utf-8"><body id="out">waiting<script>
(() => {
  const img = new Image();
  img.onload = () => {
    try {
      const canvas = document.createElement('canvas');
      canvas.width = img.naturalWidth; canvas.height = img.naturalHeight;
      const context = canvas.getContext('2d', { willReadFrequently: true });
      context.drawImage(img, 0, 0);
      const data = context.getImageData(0, 0, canvas.width, canvas.height).data;
      const bytes = new Uint8Array(data.buffer, data.byteOffset, data.byteLength);
      let binary = '';
      const CHUNK = 0x8000;
      for (let i = 0; i < bytes.length; i += CHUNK) {
        binary += String.fromCharCode.apply(null, bytes.subarray(i, Math.min(i + CHUNK, bytes.length)));
      }
      document.body.textContent = JSON.stringify({ width: canvas.width, height: canvas.height, rgbaBase64: btoa(binary) });
    } catch (error) { document.body.textContent = 'ERROR:' + error.message; }
  };
  img.onerror = () => { document.body.textContent = 'ERROR:image-load'; };
  img.src = 'data:image/webp;base64,${webpBytes.toString('base64')}';
})();
</script>`
  writeFileSync(htmlPath, html)
  try {
    const result = execFileSync(chromium, [
      '--disable-gpu', '--allow-file-access-from-files', '--virtual-time-budget=10000', '--dump-dom', `file://${htmlPath}`,
    ], { encoding: 'utf8', timeout: 30000, stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 200 * 1024 * 1024 })
    const match = result.match(/<body id="out">([\s\S]*?)<\/body>/)
    if (!match) throw new Error('Chromium output missing decoded RGBA body')
    const text = match[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&')
    if (text.startsWith('ERROR:')) throw new Error(text)
    const decoded = JSON.parse(text)
    if (decoded.width !== CANONICAL_WIDTH || decoded.height !== CANONICAL_HEIGHT) {
      throw new Error(`Canonical decode dimensions mismatch: expected ${CANONICAL_WIDTH}x${CANONICAL_HEIGHT}, got ${decoded.width}x${decoded.height}`)
    }
    return {
      sourceSha256,
      width: decoded.width,
      height: decoded.height,
      rgba: Buffer.from(decoded.rgbaBase64, 'base64'),
    }
  } finally {
    try { unlinkSync(htmlPath) } catch {}
  }
}

export function pixelBoundsFromRuns(runs) {
  let minX = Infinity
  let minY = Infinity
  let maxX = -1
  let maxY = -1
  for (const [y, xStart, xEnd] of runs) {
    if (y < minY) minY = y
    if (y > maxY) maxY = y
    if (xStart < minX) minX = xStart
    if (xEnd - 1 > maxX) maxX = xEnd - 1
  }
  if (maxX < 0) throw new Error('ownershipRuns contain no pixels')
  return { x: minX, y: minY, width: maxX - minX + 1, height: maxY - minY + 1 }
}

export function runPixelCount(runs) {
  return runs.reduce((sum, [, xStart, xEnd]) => sum + xEnd - xStart, 0)
}

/**
 * Builds one transparent-bordered sprite per fragment. Only ownershipRuns are
 * copied from canonical RGBA; every other sprite pixel stays rgba(0,0,0,0).
 */
export function buildFragmentSprites(spec, canonicalRgba, { width, height, extrusion = EXTRUSION_PIXELS } = {}) {
  const sprites = new Map()
  for (const fragment of spec.fragments) {
    const bounds = pixelBoundsFromRuns(fragment.ownershipRuns)
    const spriteWidth = bounds.width + 2 * extrusion
    const spriteHeight = bounds.height + 2 * extrusion
    const data = Buffer.alloc(spriteWidth * spriteHeight * 4)
    for (const [y, xStart, xEnd] of fragment.ownershipRuns) {
      for (let x = xStart; x < xEnd; x++) {
        const source = (y * width + x) * 4
        const target = ((y - bounds.y + extrusion) * spriteWidth + (x - bounds.x + extrusion)) * 4
        data[target] = canonicalRgba[source]
        data[target + 1] = canonicalRgba[source + 1]
        data[target + 2] = canonicalRgba[source + 2]
        data[target + 3] = canonicalRgba[source + 3]
      }
    }
    sprites.set(fragment.stableId, {
      stableId: fragment.stableId,
      homeRegion: fragment.homeRegion,
      pixelBounds: bounds,
      spriteWidth,
      spriteHeight,
      data,
      ownedOpaquePixelCount: runPixelCount(fragment.ownershipRuns),
    })
  }
  return sprites
}

/**
 * Deterministic shelf packing for one atlas. Fragments are packed in spec
 * (stableId) order, left-to-right, top-to-bottom; atlas width mirrors the home
 * region chunk width. Returns the atlas buffer and per-fragment placements.
 */
export function packRegionAtlas(fragments, sprites, { extrusion = EXTRUSION_PIXELS } = {}) {
  if (fragments.length === 0) throw new Error('cannot pack an empty region atlas')
  const region = fragments[0].homeRegion
  if (fragments.some(fragment => fragment.homeRegion !== region)) {
    throw new Error(`packRegionAtlas received mixed homeRegions for ${region}`)
  }
  const atlasWidth = regionAtlasWidth(region)
  const placements = []
  let shelfY = 0
  let shelfHeight = 0
  let shelfX = 0
  for (const fragment of fragments) {
    const sprite = sprites.get(fragment.stableId)
    if (!sprite) throw new Error(`missing sprite for ${fragment.stableId}`)
    if (shelfX + sprite.spriteWidth > atlasWidth) {
      shelfY += shelfHeight
      shelfX = 0
      shelfHeight = 0
    }
    placements.push({
      stableId: fragment.stableId,
      x: shelfX,
      y: shelfY,
      width: sprite.spriteWidth,
      height: sprite.spriteHeight,
      pixelBounds: { ...sprite.pixelBounds },
      ownedOpaquePixelCount: sprite.ownedOpaquePixelCount,
    })
    shelfX += sprite.spriteWidth
    shelfHeight = Math.max(shelfHeight, sprite.spriteHeight)
  }
  const atlasHeight = shelfY + shelfHeight
  const data = Buffer.alloc(atlasWidth * atlasHeight * 4)
  for (const placement of placements) {
    const sprite = sprites.get(placement.stableId)
    for (let y = 0; y < sprite.spriteHeight; y++) {
      const sourceOffset = y * sprite.spriteWidth * 4
      sprite.data.copy(data, ((placement.y + y) * atlasWidth + placement.x) * 4, sourceOffset, sourceOffset + sprite.spriteWidth * 4)
    }
  }
  return { region, width: atlasWidth, height: atlasHeight, data, placements }
}

export function encodePng(width, height, rgba, options = PNG_ENCODE_OPTIONS) {
  const png = new PNG({ width, height, colorType: 6, bitDepth: 8 })
  Buffer.from(rgba.buffer, rgba.byteOffset, rgba.byteLength).copy(png.data)
  // pngjs mutates the options object (deflateChunkSize etc.); pass a copy so
  // the frozen constant stays immutable and the encoding stays deterministic.
  return PNG.sync.write(png, { ...options })
}

export function decodePng(bytes) {
  const png = PNG.sync.read(bytes)
  return { width: png.width, height: png.height, rgba: png.data }
}

/**
 * Reconstructs the full canonical frame from decoded atlas textures using only
 * manifest data (atlasRect + pixelBounds + destination mapping). Non-owned
 * pixels are transparent and are skipped by the alpha>0 test.
 */
export function reconstructFromManifest(manifest, decodedAtlases, { width = CANONICAL_WIDTH, height = CANONICAL_HEIGHT } = {}) {
  const canvas = Buffer.alloc(width * height * 4)
  const coverage = new Int32Array(width * height).fill(-1)
  const atlasByFile = new Map(decodedAtlases.map(atlas => [atlas.file, atlas]))
  let placementIndex = 0
  for (const mapping of manifest.fragments) {
    const atlas = atlasByFile.get(mapping.atlasFile)
    if (!atlas) throw new Error(`missing decoded atlas for ${mapping.atlasFile}`)
    const rect = mapping.atlasRect
    const bounds = mapping.pixelBounds
    const extrusion = mapping.extrusionPixels
    for (let y = 0; y < bounds.height; y++) {
      for (let x = 0; x < bounds.width; x++) {
        const atlasIndex = ((rect.y + extrusion + y) * atlas.width + (rect.x + extrusion + x)) * 4
        const alpha = atlas.rgba[atlasIndex + 3]
        if (alpha === 0) continue
        const targetX = bounds.x + x
        const targetY = bounds.y + y
        if (targetX < 0 || targetX >= width || targetY < 0 || targetY >= height) {
          throw new Error(`${mapping.stableId} reconstruction target out of bounds (${targetX},${targetY})`)
        }
        const canvasIndex = (targetY * width + targetX) * 4
        canvas[canvasIndex] = atlas.rgba[atlasIndex]
        canvas[canvasIndex + 1] = atlas.rgba[atlasIndex + 1]
        canvas[canvasIndex + 2] = atlas.rgba[atlasIndex + 2]
        canvas[canvasIndex + 3] = atlas.rgba[atlasIndex + 3]
        coverage[targetY * width + targetX] = placementIndex
      }
    }
    placementIndex++
  }
  return { canvas, coverage }
}

/** Counts canonical transparent pixels whose RGB is non-zero (the explicit transparent-RGB policy check). */
export function transparentRgbAnalysis(rgba, { width = CANONICAL_WIDTH, height = CANONICAL_HEIGHT } = {}) {
  let alpha0NonZeroRgb = 0
  const samples = []
  for (let index = 0; index < width * height; index++) {
    const offset = index * 4
    if (rgba[offset + 3] !== 0) continue
    if (rgba[offset] !== 0 || rgba[offset + 1] !== 0 || rgba[offset + 2] !== 0) {
      alpha0NonZeroRgb++
      if (samples.length < 10) samples.push({ x: index % width, y: Math.floor(index / width), r: rgba[offset], g: rgba[offset + 1], b: rgba[offset + 2] })
    }
  }
  return { alpha0NonZeroRgb, samples }
}

/**
 * Pixel-exact golden comparison between canonical and reconstructed RGBA.
 * missing = canonical opaque pixel absent from reconstruction;
 * overlap  = canonical transparent pixel that reconstruction made opaque
 *            (duplicate/extra content) plus spec-run ownership overlaps;
 * channelMismatch = any RGBA channel differs at any pixel.
 */
export function compareGolden(canonicalRgba, reconstructed, spec, { width = CANONICAL_WIDTH, height = CANONICAL_HEIGHT } = {}) {
  let missing = 0
  let overlap = 0
  let channelMismatch = 0
  const byChannel = { r: 0, g: 0, b: 0, a: 0 }
  const owner = new Int32Array(width * height).fill(-1)
  for (let fragmentIndex = 0; fragmentIndex < spec.fragments.length; fragmentIndex++) {
    for (const [y, xStart, xEnd] of spec.fragments[fragmentIndex].ownershipRuns) {
      for (let x = xStart; x < xEnd; x++) {
        const index = y * width + x
        if (owner[index] !== -1 && owner[index] !== fragmentIndex) overlap++
        owner[index] = fragmentIndex
      }
    }
  }
  for (let index = 0; index < width * height; index++) {
    const offset = index * 4
    const canonicalAlpha = canonicalRgba[offset + 3]
    const reconstructedAlpha = reconstructed[offset + 3]
    if (canonicalAlpha > 0 && reconstructedAlpha === 0) missing++
    if (canonicalAlpha === 0 && reconstructedAlpha > 0) overlap++
    if (canonicalRgba[offset] !== reconstructed[offset]) { channelMismatch++; byChannel.r++ }
    if (canonicalRgba[offset + 1] !== reconstructed[offset + 1]) { channelMismatch++; byChannel.g++ }
    if (canonicalRgba[offset + 2] !== reconstructed[offset + 2]) { channelMismatch++; byChannel.b++ }
    if (canonicalRgba[offset + 3] !== reconstructed[offset + 3]) { channelMismatch++; byChannel.a++ }
  }
  const transparent = transparentRgbAnalysis(canonicalRgba, { width, height })
  return {
    passed: missing === 0 && overlap === 0 && channelMismatch === 0,
    comparedPixels: width * height,
    missingPixels: missing,
    overlapPixels: overlap,
    channelMismatchPixels: channelMismatch,
    channelMismatchByChannel: byChannel,
    transparentRgb: {
      policy: 'non-owned pixels are cleared to rgba(0,0,0,0); canonical transparent pixels are also rgba(0,0,0,0)',
      canonicalAlpha0NonZeroRgb: transparent.alpha0NonZeroRgb,
      samples: transparent.samples,
    },
  }
}

/**
 * Deterministic straight-alpha bilinear scaler used for zoom seam evidence.
 * The same function is applied to canonical and reconstructed inputs, so any
 * scaler systematic behavior cancels in the comparison.
 */
export function scaleBilinear(source, sourceWidth, sourceHeight, targetWidth, targetHeight) {
  if (targetWidth <= 0 || targetHeight <= 0) throw new Error('scaled crop dimensions must be positive')
  const out = Buffer.alloc(targetWidth * targetHeight * 4)
  for (let targetY = 0; targetY < targetHeight; targetY++) {
    const sourceY = (targetY + 0.5) * sourceHeight / targetHeight - 0.5
    const clampedY = Math.min(Math.max(sourceY, 0), sourceHeight - 1)
    const y0 = Math.floor(clampedY)
    const y1 = Math.min(y0 + 1, sourceHeight - 1)
    const fy = clampedY - y0
    for (let targetX = 0; targetX < targetWidth; targetX++) {
      const sourceX = (targetX + 0.5) * sourceWidth / targetWidth - 0.5
      const clampedX = Math.min(Math.max(sourceX, 0), sourceWidth - 1)
      const x0 = Math.floor(clampedX)
      const x1 = Math.min(x0 + 1, sourceWidth - 1)
      const fx = clampedX - x0
      const outputIndex = (targetY * targetWidth + targetX) * 4
      for (let channel = 0; channel < 4; channel++) {
        const p00 = source[(y0 * sourceWidth + x0) * 4 + channel]
        const p10 = source[(y0 * sourceWidth + x1) * 4 + channel]
        const p01 = source[(y1 * sourceWidth + x0) * 4 + channel]
        const p11 = source[(y1 * sourceWidth + x1) * 4 + channel]
        const top = p00 + (p10 - p00) * fx
        const bottom = p01 + (p11 - p01) * fx
        const value = top + (bottom - top) * fy
        const rounded = Math.round(value)
        out[outputIndex + channel] = rounded < 0 ? 0 : rounded > 255 ? 255 : rounded
      }
    }
  }
  return out
}

export function cropRgba(source, sourceWidth, sourceHeight, rect) {
  if (rect.x < 0 || rect.y < 0 || rect.x + rect.width > sourceWidth || rect.y + rect.height > sourceHeight) {
    throw new Error(`crop out of bounds: ${JSON.stringify(rect)} on ${sourceWidth}x${sourceHeight}`)
  }
  const out = Buffer.alloc(rect.width * rect.height * 4)
  for (let y = 0; y < rect.height; y++) {
    const sourceOffset = ((rect.y + y) * sourceWidth + rect.x) * 4
    Buffer.from(source.buffer, source.byteOffset + sourceOffset, rect.width * 4).copy(out, y * rect.width * 4)
  }
  return out
}

export function scaledCropComparison(canonicalRgba, reconstructed, rect, zoomLabel, { width = CANONICAL_WIDTH, height = CANONICAL_HEIGHT } = {}) {
  const factor = ZOOM_FACTORS[zoomLabel]
  if (factor === undefined) throw new Error(`unknown zoom ${zoomLabel}`)
  const targetWidth = Math.round(rect.width * factor)
  const targetHeight = Math.round(rect.height * factor)
  const canonicalCrop = cropRgba(canonicalRgba, width, height, rect)
  const reconstructedCrop = cropRgba(reconstructed, width, height, rect)
  const canonicalScaled = scaleBilinear(canonicalCrop, rect.width, rect.height, targetWidth, targetHeight)
  const reconstructedScaled = scaleBilinear(reconstructedCrop, rect.width, rect.height, targetWidth, targetHeight)
  let mismatchPixels = 0
  let maxChannelDelta = 0
  for (let index = 0; index < targetWidth * targetHeight; index++) {
    const offset = index * 4
    let pixelMismatch = false
    for (let channel = 0; channel < 4; channel++) {
      const delta = Math.abs(canonicalScaled[offset + channel] - reconstructedScaled[offset + channel])
      if (delta > maxChannelDelta) maxChannelDelta = delta
      if (delta !== 0) pixelMismatch = true
    }
    if (pixelMismatch) mismatchPixels++
  }
  return {
    zoom: zoomLabel,
    cropRect: { ...rect },
    sourcePixels: rect.width * rect.height,
    targetWidth,
    targetHeight,
    targetPixels: targetWidth * targetHeight,
    exact: mismatchPixels === 0 && maxChannelDelta === 0,
    mismatchPixels,
    maxChannelDelta,
    canonicalScaled,
    reconstructedScaled,
  }
}

export function diffRgba(canonical, reconstructed) {
  if (canonical.length !== reconstructed.length) throw new Error('diff inputs must have equal byte length')
  const out = Buffer.alloc(canonical.length)
  for (let index = 0; index < canonical.length; index += 4) {
    let maxDelta = 0
    for (let channel = 0; channel < 4; channel++) {
      maxDelta = Math.max(maxDelta, Math.abs(canonical[index + channel] - reconstructed[index + channel]))
    }
    if (maxDelta > 0) {
      out[index] = 255
      out[index + 1] = 0
      out[index + 2] = 0
      out[index + 3] = 255
    } else {
      out[index] = 0
      out[index + 1] = 0
      out[index + 2] = 0
      out[index + 3] = 255
    }
  }
  return out
}

export function pngDataUri(width, height, rgba) {
  const bytes = encodePng(width, height, rgba)
  return `data:image/png;base64,${bytes.toString('base64')}`
}

export function buildSeamContactSheet(focus, zooms, canonicalRgba, reconstructed) {
  const cellGap = 8
  const labelHeight = 22
  const labelWidth = 72
  const cells = []
  for (const zoom of zooms) {
    const comparison = scaledCropComparison(canonicalRgba, reconstructed, focus.crop, zoom)
    // canonicalScaled and reconstructedScaled are pixel-identical whenever the
    // golden holds; the single column is labeled accordingly and each zoom row
    // carries an exact-match verdict. Authoritative diff statistics live in
    // seam-evidence-report.json.
    cells.push({ zoom, comparison, render: pngDataUri(comparison.targetWidth, comparison.targetHeight, comparison.canonicalScaled) })
  }
  const maxCellWidth = Math.max(...cells.map(cell => cell.comparison.targetWidth))
  const width = labelWidth + maxCellWidth + cellGap * 2
  let cursorY = labelHeight + cellGap
  const rows = []
  for (let rowIndex = 0; rowIndex < cells.length; rowIndex++) {
    const cell = cells[rowIndex]
    const cellHeight = cell.comparison.targetHeight
    rows.push({ ...cell, y: cursorY, height: cellHeight, rowIndex })
    cursorY += cellHeight + cellGap
  }
  const height = cursorY + 24
  const parts = []
  parts.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"`)
  parts.push(` data-task-id="E9B" data-generation-id="${E9A_GENERATION_ID}"`)
  parts.push(` data-focus-id="${focus.id}" data-focus-index="${focus.index}" data-focus-label="${escapeXml(focus.label)}"`)
  parts.push(` data-stable-id="${focus.stableId}" data-zoom-count="${zooms.length}" data-canvas="1664x928"`)
  parts.push(` data-column="canonical-equivalent-reconstructed">`)
  parts.push(`<rect width="${width}" height="${height}" fill="#ffffff"/>`)
  parts.push(`<text x="8" y="16" font-family="monospace" font-size="11" fill="#000000">E9B seam evidence · focus ${focus.index}/4 ${escapeXml(focus.label)} · crop ${focus.crop.x},${focus.crop.y} ${focus.crop.width}x${focus.crop.height} · stableId ${focus.stableId}</text>`)
  parts.push(`<text x="8" y="${labelHeight + 8}" font-family="monospace" font-size="10" fill="#444444">canonical ≡ reconstructed (golden exact 0/0/0); diff stats: seam-evidence-report.json</text>`)
  for (const row of rows) {
    parts.push(`<text x="8" y="${row.y + row.height / 2 + 4}" font-family="monospace" font-size="11" fill="#000000">${row.zoom}×</text>`)
    parts.push(`<text x="8" y="${row.y + row.height / 2 + 18}" font-family="monospace" font-size="9" fill="#666666">zoom ${row.rowIndex + 1}/5</text>`)
    const imageX = labelWidth + cellGap
    parts.push(`<image data-zoom-index="${row.rowIndex + 1}" data-zoom="${row.zoom}" href="${row.render}" x="${imageX}" y="${row.y}" width="${row.comparison.targetWidth}" height="${row.height}"/>`)
    parts.push(`<text x="${imageX}" y="${row.y + row.height + 10}" font-family="monospace" font-size="9" fill="${row.comparison.exact ? '#006600' : '#cc0000'}">${row.comparison.exact ? 'exact match' : `${row.comparison.mismatchPixels} px mismatch`}</text>`)
  }
  parts.push(`</svg>`)
  return { svg: parts.join(''), cells }
}

function escapeXml(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

