export function computeManifestId(manifest) {
  const clone = structuredClone(manifest)
  delete clone.manifestId
  return sha256(stableStringify(clone))
}

export function buildManifest(spec, atlases, sprites, packingOrder, canonicalSha256, canonicalBytes, generatorInfo) {
  const atlasEntries = REGION_ORDER.map(region => {
    const atlas = atlases.get(region)
    if (!atlas) throw new Error(`missing atlas for region ${region}`)
    return {
      region,
      file: atlasFilePath(region),
      sha256: sha256(atlas.bytes),
      width: atlas.width,
      height: atlas.height,
      bytes: atlas.bytes.length,
      fragmentCount: atlas.placements.length,
      packingOrder: atlas.placements.map(placement => placement.stableId),
    }
  })
  const fragments = spec.fragments.map(fragment => {
    const sprite = sprites.get(fragment.stableId)
    if (!sprite) throw new Error(`missing sprite for ${fragment.stableId}`)
    const region = fragment.homeRegion
    const atlas = atlases.get(region)
    const placement = atlas.placements.find(candidate => candidate.stableId === fragment.stableId)
    if (!placement) throw new Error(`missing placement for ${fragment.stableId}`)
    return {
      stableId: fragment.stableId,
      homeRegion: fragment.homeRegion,
      atlasFile: atlasFilePath(region),
      atlasRect: { x: placement.x, y: placement.y, width: placement.width, height: placement.height },
      pixelBounds: { ...placement.pixelBounds },
      sourceRect: { ...fragment.sourceRect },
      destinationRect: { ...fragment.destinationRect },
      destinationMapping: { ...fragment.destinationMapping },
      paddingPixels: PADDING_PIXELS,
      extrusionPixels: EXTRUSION_PIXELS,
      encoding: FORMAT_CHOICE.chosen,
      ownedOpaquePixelCount: fragment.ownedOpaquePixelCount,
      packingOrderIndex: packingOrder.get(fragment.stableId),
    }
  })
  const manifest = {
    $schema: 'jyt.occlusion.atlas-manifest.v1',
    schemaVersion: 1,
    taskId: 'E9B',
    e9aGenerationId: E9A_GENERATION_ID,
    e9aSpecPath: E9A_SPEC_PATH,
    canonical: {
      assetRef: 'jyt.occlusion-source.hall-v3',
      path: CANONICAL_PATH,
      sha256: canonicalSha256,
      width: CANONICAL_WIDTH,
      height: CANONICAL_HEIGHT,
      alphaThreshold: ALPHA_THRESHOLD,
      totalOpaquePixels: spec.sourceProvenance.totalOpaquePixels,
    },
    e8bTmx: {
      taskId: 'E8B',
      path: 'public/juyiting/hall.tmx',
      sha256: E8B_TMX_SHA256,
    },
    generator: generatorInfo,
    encoding: {
      format: FORMAT_CHOICE.chosen,
      lossless: true,
      colorType: 6,
      bitDepth: 8,
      alpha: true,
      deflateLevel: PNG_ENCODE_OPTIONS.deflateLevel,
      deflateStrategy: PNG_ENCODE_OPTIONS.deflateStrategy,
      filterType: PNG_ENCODE_OPTIONS.filterType,
      formatChoiceRationale: FORMAT_CHOICE.rationale,
      specAllowedFormats: [...spec.outputConstraints.formats],
    },
    packing: {
      algorithm: 'deterministic-shelf',
      orderBasis: 'spec stableId order (spec.fragments order)',
      atlasWidthBasis: 'home region chunk width',
      paddingPixels: PADDING_PIXELS,
      extrusionPixels: EXTRUSION_PIXELS,
    },
    atlases: atlasEntries,
    fragments,
    packingOrder: Object.fromEntries(REGION_ORDER.map(region => [region, atlasEntries.find(entry => entry.region === region).packingOrder])),
    generationId: E9A_GENERATION_ID,
    note: 'lossless deterministic PNG chosen because no lossless WebP encoder is verifiable on this host; regeneration is byte-identical',
  }
  manifest.manifestId = computeManifestId(manifest)
  return manifest
}

export function buildGoldenReport(manifest, golden, canonicalRgba, atlases, canonicalBytes, reconstructedBytes) {
  const decodedTextureArea = atlases.reduce((sum, atlas) => sum + atlas.width * atlas.height, 0)
  const networkBytes = atlases.reduce((sum, atlas) => sum + atlas.bytes, 0)
  const spriteArea = atlases.reduce((sum, atlas) => sum + atlas.placements.reduce((inner, placement) => inner + placement.width * placement.height, 0), 0)
  const reconstructed = transparentRgbAnalysis(reconstructedBytes, { width: CANONICAL_WIDTH, height: CANONICAL_HEIGHT })
  return {
    $schema: 'jyt.occlusion.rgba-golden-report.v1',
    schemaVersion: 1,
    taskId: 'E9B',
    e9aGenerationId: manifest.e9aGenerationId,
    manifestId: manifest.manifestId,
    source: {
      assetRef: manifest.canonical.assetRef,
      sha256: manifest.canonical.sha256,
      width: manifest.canonical.width,
      height: manifest.canonical.height,
      alphaThreshold: manifest.canonical.alphaThreshold,
      totalOpaquePixels: manifest.canonical.totalOpaquePixels,
    },
    golden,
    transparentRgbPolicy: {
      policy: golden.transparentRgb.policy,
      canonicalAlpha0NonZeroRgb: golden.transparentRgb.canonicalAlpha0NonZeroRgb,
      reconstructedAlpha0NonZeroRgb: reconstructed.alpha0NonZeroRgb,
      samples: golden.transparentRgb.samples,
    },
    metrics: {
      networkBytes,
      networkBytesByAtlas: Object.fromEntries(atlases.map(atlas => [atlas.region, atlas.bytes])),
      canonicalSourceBytes: canonicalBytes.length,
      networkVsCanonicalRatio: Number((networkBytes / canonicalBytes.length).toFixed(3)),
      decodedTextureAreaPx: decodedTextureArea,
      fullFramePixels: CANONICAL_WIDTH * CANONICAL_HEIGHT,
      packedSpriteAreaPx: spriteArea,
      packingEfficiency: Number((spriteArea / decodedTextureArea).toFixed(4)),
      uncompressedRgbaBytes: CANONICAL_WIDTH * CANONICAL_HEIGHT * 4,
      atlasCount: atlases.length,
      fragmentCount: manifest.fragments.length,
    },
    reconstruction: {
      width: CANONICAL_WIDTH,
      height: CANONICAL_HEIGHT,
      method: 'independent pngjs decode of each atlas + manifest placement',
    },
  }
}
